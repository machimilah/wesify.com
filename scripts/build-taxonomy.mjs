import { readFile, writeFile } from 'node:fs/promises'

/**
 * Regenerates BO's industry taxonomy module from the vendored NAICS source.
 *
 * NAICS is published by the US Census Bureau and is a work of the US federal government — public
 * domain, redistributable. It is the only part of BO's knowledge base that is imported rather than
 * authored, and it is imported because enumerating every kind of business is exactly the problem it
 * already solves: 20 sectors, 96 subsectors, 1,012 national industries.
 *
 * Refresh with: node scripts/build-taxonomy.mjs
 */

const source = JSON.parse(await readFile('data/sources/naics-2022.json', 'utf8'))

const clean = title => title.replace(/\s+/g, ' ').replace(/T$/, '').trim()
const level = code => code.split('-')[0].length

const sectors = source.filter(item => level(item.code) === 2).map(item => ({ code: item.code, title: clean(item.title) }))
const subsectors = source.filter(item => level(item.code) === 3).map(item => ({ code: item.code, title: clean(item.title) }))
// Every title at every level is search surface. "Nail Salons" and "Title Abstract and Settlement
// Offices" are the phrases operators actually use about themselves, and they only exist at the
// deepest levels of the taxonomy.
const searchIndex = source
  .filter(item => level(item.code) >= 3)
  .map(item => [item.code, clean(item.title)])
  .filter(([code, title]) => Boolean(title) && (level(code) === 3 || !/^Other |, NEC$|Not Elsewhere Classified/i.test(title)))

const module = `// GENERATED by scripts/build-taxonomy.mjs — do not edit by hand.
// Source: NAICS 2022, US Census Bureau (public domain). See docs/KNOWLEDGE_BASE.md.

export interface NaicsEntry { code: string; title: string }

/** The 20 top-level sectors: every business in the economy sits under exactly one. */
export const naicsSectors: NaicsEntry[] = ${JSON.stringify(sectors, null, 2)}

/** The 96 subsectors. This is the level at which the software a business needs actually changes. */
export const naicsSubsectors: NaicsEntry[] = ${JSON.stringify(subsectors, null, 2)}

/** Every industry title from subsector down, as [code, title] — the lexical surface for matching. */
export const naicsSearchIndex: Array<[string, string]> = ${JSON.stringify(searchIndex)}

export const naicsSectorOf = (code: string) => code.slice(0, 2)
export const naicsSubsectorOf = (code: string) => code.slice(0, 3)
`

await writeFile('src/data/naics.generated.ts', module, 'utf8')
console.log(`Taxonomy built: ${sectors.length} sectors, ${subsectors.length} subsectors, ${searchIndex.length} searchable titles.`)
